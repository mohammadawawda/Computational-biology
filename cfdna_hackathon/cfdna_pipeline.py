# Step 2: preprocessing (clean/filter)
# ----------------------------

def clean_seq(
    seq: str,
    *,
    fixed_len: Optional[int] = None,
    min_len: int = 50,
    max_len: int = 150,
    max_n_frac: float = 0.0,
    strict: bool = True,
) -> Optional[str]:
    """
    Returns cleaned uppercase sequence or None if filtered out.
    strict=True  -> drop any read with non-ACGTN
    strict=False -> replace invalid chars with 'N'
    """
    s = "".join(seq.split()).upper()
    if not s:
        return None

    if strict:
        if any(ch not in ALLOWED for ch in s):
            return None
    else:
        s = "".join(ch if ch in ALLOWED else "N" for ch in s)

    L = len(s)
    if fixed_len is not None and L != fixed_len:
        return None
    if L < min_len or L > max_len:
        return None
    if (s.count("N") / L) > max_n_frac:
        return None
    return s


def iter_reads_preprocessed(
    path: str,
    *,
    fixed_len: Optional[int] = None,
    min_len: int = 50,
    max_len: int = 150,
    max_n_frac: float = 0.0,
    strict: bool = True,
    keep_full_header: bool = False,
) -> Generator[Read, None, None]:
    """
    Unified Step 1 + Step 2:
    - opens file/zip members
    - sniffs format
    - streams reads
    - cleans & filters
    Yields Read objects.
    """
    for name, stream in iter_text_streams(path):
        fmt = sniff_format(stream)

        if fmt == "fasta":
            use_two_line = is_two_line_fasta(stream)
            it = iter_fasta_two_line(stream) if use_two_line else iter_fasta_general(stream)

            for full_header, rid, seq in it:
                cleaned = clean_seq(
                    seq,
                    fixed_len=fixed_len,
                    min_len=min_len,
                    max_len=max_len,
                    max_n_frac=max_n_frac,
                    strict=strict,
                )
                if cleaned is None:
                    continue
                yield Read(
                    rid=rid,
                    seq=cleaned,
                    qual=None,
                    header=full_header if keep_full_header else None,
                )

        else:  # fastq
            for rid, seq, qual in iter_fastq(stream):
                cleaned = clean_seq(
                    seq,
                    fixed_len=fixed_len,
                    min_len=min_len,
                    max_len=max_len,
                    max_n_frac=max_n_frac,
                    strict=strict,
                )
                if cleaned is None:
                    continue
                # (optional) also ensure qual length matches seq length
                if len(qual) != len(seq):
                    continue
                yield Read(rid=rid, seq=cleaned, qual=qual, header=None)


# ----------------------------
# Optional: write cleaned FASTA + QC summary in one pass
# ----------------------------

def preprocess_to_clean_fasta_and_qc(
    in_path: str,
    out_fasta: str,
    *,
    fixed_len: Optional[int] = None,
    min_len: int = 50,
    max_len: int = 150,
    max_n_frac: float = 0.0,
    strict: bool = True,
) -> dict:
    import collections

    qc = {
        "total_in": 0,
        "kept": 0,
        "dropped": 0,
        "length_counts": collections.Counter(),
        "base_counts": collections.Counter(),
        "n_reads_with_N": 0,
    }

    with open(out_fasta, "w", encoding="utf-8", newline="") as out:
        for r in iter_reads_preprocessed(
            in_path,
            fixed_len=fixed_len,
            min_len=min_len,
            max_len=max_len,
            max_n_frac=max_n_frac,
            strict=strict,
        ):
            qc["total_in"] += 1
            qc["kept"] += 1
            qc["length_counts"][len(r.seq)] += 1
            qc["base_counts"].update(r.seq)
            if "N" in r.seq:
                qc["n_reads_with_N"] += 1
            out.write(f">{r.rid}\n{r.seq}\n")

    # Note: total_in here is "seen after parsing"; if you want exact dropped count
    # including parsing-skipped invalid records, count separately during parsing.
    qc["length_counts"] = dict(qc["length_counts"])
    qc["base_counts"] = dict(qc["base_counts"])
    return qc

