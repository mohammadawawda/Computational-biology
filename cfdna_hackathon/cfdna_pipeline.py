import numpy as np
import pandas as pd
from statsmodels.nonparametric.smoothers_lowess import lowess
from pathlib import Path

def _find_gc_col(columns):
    # common bedtools nuc column names include "pct_gc"
    for c in columns:
        if c.lower() == "pct_gc":
            return c
    for c in columns:
        lc = c.lower()
        if "gc" in lc and ("pct" in lc or "%" in lc):
            return c
    # sometimes bedtools output uses "GC" variants
    for c in columns:
        if "gc" in c.lower():
            return c
    return None

def step7_gc_correct_and_normalize(counts_tsv: str, gc_tsv: str, out_tsv: str, lowess_frac: float = 0.2):
    # Step 5 counts: BED + last column is counts
    c = pd.read_csv(counts_tsv, sep="\t", header=None)
    c = c.rename(columns={0:"chrom", 1:"start", 2:"end", c.columns[-1]:"count"})
    c = c[["chrom", "start", "end", "count"]]

    # Step 6 GC: bedtools nuc has a header row; first 3 columns are chrom/start/end
    g = pd.read_csv(gc_tsv, sep="\t")
    gc_col = _find_gc_col(g.columns)
    if gc_col is None:
        raise ValueError(f"Could not find GC column in bedtools nuc output. Columns: {list(g.columns)}")

    g = g.rename(columns={g.columns[0]:"chrom", g.columns[1]:"start", g.columns[2]:"end", gc_col:"pct_gc"})
    g = g[["chrom", "start", "end", "pct_gc"]]

    df = c.merge(g, on=["chrom","start","end"], how="inner").copy()

    # Drop bins with zero counts (log undefined); keep track if needed
    df = df[df["count"] > 0].copy()

    # LOWESS fit: log(count) ~ GC%
    x = df["pct_gc"].astype(float).values
    y = np.log(df["count"].astype(float).values)

    fitted = lowess(y, x, frac=lowess_frac, return_sorted=False)

    # Convert fit to multiplicative bias curve
    bias = np.exp(fitted - np.mean(fitted))
    df["gc_corrected"] = df["count"] / bias

    # Normalize by autosomal total (chr1..chr22), robust to "1" vs "chr1"
    def canon_chr(s):
        s = str(s)
        return s if s.startswith("chr") else "chr" + s

    df["chrom_canon"] = df["chrom"].map(canon_chr)
    autosomes = {f"chr{i}" for i in range(1,23)}
    denom = df.loc[df["chrom_canon"].isin(autosomes), "gc_corrected"].sum()

    df["norm_prop"] = df["gc_corrected"] / denom if denom > 0 else np.nan

    out_tsv = Path(out_tsv)
    out_tsv.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_tsv, sep="\t", index=False)
    return str(out_tsv)

