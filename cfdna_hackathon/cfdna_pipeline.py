def align_fasta_to_sam_only(
    fasta_path: str,
    ref_fasta_path: str,
    sam_out_path: str,
    threads: int = 4
) -> str:
    """
    STEP 3 (ALIGNMENT): FASTA -> SAM using BWA-MEM

    Inputs:
      - fasta_path: reads in FASTA format
      - ref_fasta_path: reference genome FASTA (hg38.fa or toy_ref.fa)
      - sam_out_path: where to write output SAM
      - threads: bwa threads

    Output:
      - SAM file (text) where each read has RNAME (chrom), POS, MAPQ, etc.
    """
    # Tools must exist
    if shutil.which("bwa") is None:
        raise RuntimeError("bwa not found. Run install_bwa_samtools_colab() first.")

    fasta_path = Path(fasta_path)
    ref_fasta_path = Path(ref_fasta_path)
    sam_out_path = Path(sam_out_path)
    sam_out_path.parent.mkdir(parents=True, exist_ok=True)

    # Validate files exist
    if not fasta_path.exists():
        raise FileNotFoundError(f"Reads FASTA not found: {fasta_path}")
    if not ref_fasta_path.exists():
        raise FileNotFoundError(
            f"Reference FASTA not found: {ref_fasta_path}\n"
            f"Step 3 requires a reference FASTA (hg38.fa or a toy reference)."
        )

    # Index reference if needed
    index_files = [str(ref_fasta_path) + ext for ext in [".amb", ".ann", ".bwt", ".pac", ".sa"]]
    if not all(Path(x).exists() for x in index_files):
        _run(f"bwa index '{ref_fasta_path}'")

    # Align -> SAM
    _run(f"bwa mem -t {threads} '{ref_fasta_path}' '{fasta_path}' > '{sam_out_path}'")
    return str(sam_out_path)

