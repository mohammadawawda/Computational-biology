def step4_sam_to_sorted_bam(sam_path: str, bam_out_prefix: str) -> tuple[str, str]:
    """
    STEP 4:
    Input : SAM file (from Step 3)
    Output: sorted BAM + BAI (index)

    Returns:
      (sorted_bam_path, bai_path)
    """
    if shutil.which("samtools") is None:
        raise RuntimeError("samtools not found. Run install_bwa_samtools_colab() first.")

    sam_path = Path(sam_path)
    if not sam_path.exists():
        raise FileNotFoundError(f"SAM not found: {sam_path}")

    bam_out_prefix = Path(bam_out_prefix)
    bam_out_prefix.parent.mkdir(parents=True, exist_ok=True)

    bam_path = str(bam_out_prefix) + ".bam"
    sorted_bam_path = str(bam_out_prefix) + ".sorted.bam"
    bai_path = sorted_bam_path + ".bai"

    # Convert SAM -> BAM
    _run(f"samtools view -bS '{sam_path}' > '{bam_path}'")

    # Sort BAM
    _run(f"samtools sort '{bam_path}' -o '{sorted_bam_path}'")

    # Index BAM
    _run(f"samtools index '{sorted_bam_path}'")

    return sorted_bam_path, bai_path

