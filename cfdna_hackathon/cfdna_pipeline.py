import pandas as pd
import numpy as np

def load_baseline(baseline_tsv: str, metric="chr21_prop"):
    b = pd.read_csv(baseline_tsv, sep="\t")
    row = b.loc[b["metric"] == metric].iloc[0]
    return float(row["mean"]), float(row["std"]), int(row["n"])

def z_score(step7_tsv: str, baseline_tsv: str, chrom="chr21"):
    metric = f"{chrom}_prop"
    mu, sd, n = load_baseline(baseline_tsv, metric=metric)
    x = chr_prop(step7_tsv, chrom)
    z = (x - mu) / sd if sd > 0 else np.nan
    return x, mu, sd, n, z

