import pysam
import pandas as pd
from pathlib import Path

def step5_bin_counts(
    sorted_bam_path: str,
    bin_size: int,
    out_csv_path: str,
    mapq_threshold: int = 0
):
    """
    STEP 5: Count reads per genomic bin.

    Inputs:
      - sorted_bam_path: sorted BAM from Step 4
      - bin_size: bin size in bp (e.g. 100_000)
      - out_csv_path: where to write bin counts (CSV)
      - mapq_threshold: minimum MAPQ to include a read

    Output:
      CSV with columns:
        chromosome | bin_start | bin_end | read_count
    """

    sorted_bam_path = Path(sorted_bam_path)
    out_csv_path = Path(out_csv_path)
    out_csv_path.parent.mkdir(parents=True, exist_ok=True)

    if not sorted_bam_path.exists():
        raise FileNotFoundError(f"BAM not found: {sorted_bam_path}")

    bam = pysam.AlignmentFile(sorted_bam_path, "rb")

    rows = []

    for chrom in bam.references:
        chrom_len = bam.get_reference_length(chrom)
        n_bins = (chrom_len + bin_size - 1) // bin_size

        # initialize bins
        counts = [0] * n_bins

        for read in bam.fetch(chrom):
            if read.is_unmapped:
                continue
            if read.mapping_quality < mapq_threshold:
                continue

            pos = read.reference_start  # 0-based
            bin_idx = pos // bin_size
            counts[bin_idx] += 1

        for i, c in enumerate(counts):
            rows.append({
                "chromosome": chrom,
                "bin_start": i * bin_size,
                "bin_end": min((i + 1) * bin_size, chrom_len),
                "read_count": c
            })

    bam.close()

    df = pd.DataFrame(rows)
    df.to_csv(out_csv_path, index=False)

    return df

