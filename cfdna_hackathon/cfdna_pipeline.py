from __future__ import annotations
from dataclasses import dataclass
from typing import Generator, Iterable, Optional, TextIO, Tuple, Union
import io
import os
import gzip
import zipfile

ALLOWED = set("ACGTN")

@dataclass
class Read:
    rid: str           # read id (safe token)
    seq: str           # sequence (uppercase, no whitespace)
    qual: Optional[str] = None   # FASTQ quality string (if present)
    header: Optional[str] = None # original header (optional, for traceability)


# ----------------------------
# Step 1: open input efficiently
# ----------------------------

def _open_text(path: str) -> TextIO:
    """
    Open a local file as text efficiently.
    Supports: plain text and .gz
    """
    if path.endswith(".gz"):
        return io.TextIOWrapper(gzip.open(path, "rb"), encoding="utf-8", newline="")
    return open(path, "r", encoding="utf-8", newline="")


def iter_text_streams(path: str) -> Generator[Tuple[str, TextIO], None, None]:
    """
    Yields (stream_name, text_stream) for:
    - a normal file (one stream)
    - a .zip containing one or more members (one stream per member)
    """
    if path.endswith(".zip"):
        zf = zipfile.ZipFile(path, "r")
        # Only consider file-like members (skip dirs)
        members = [m for m in zf.namelist() if not m.endswith("/")]
        for m in members:
            # Stream member as text
            raw = zf.open(m, "r")
            txt = io.TextIOWrapper(raw, encoding="utf-8", newline="")
            yield m, txt
            txt.close()
        zf.close()
    else:
        f = _open_text(path)
        try:
            yield os.path.basename(path), f
        finally:
            f.close()


def sniff_format(stream: TextIO) -> str:
    """
    Peek first non-empty line to determine FASTA vs FASTQ.
    Returns "fasta" or "fastq".
    """
    pos = stream.tell()
    first = ""
    while True:
        line = stream.readline()
        if not line:
            break
        line = line.strip()
        if line:
            first = line
            break
    stream.seek(pos)
    if first.startswith(">"):
        return "fasta"
    if first.startswith("@"):
        return "fastq"
    raise ValueError("Unknown format: file does not look like FASTA (>) or FASTQ (@).")


# ----------------------------
# FASTA readers (streaming)
# ----------------------------

def iter_fasta_general(stream: TextIO) -> Generator[Tuple[str, str, str], None, None]:
    """
    General FASTA parser:
    Yields (full_header, rid_token, seq_concat).
    Works even if sequences are wrapped across multiple lines.
    """
    header = None
    seq_parts = []
    for line in stream:
        line = line.strip()
        if not line:
            continue
        if line.startswith(">"):
            if header is not None:
                full = header
                rid = full.split()[0]
                yield full, rid, "".join(seq_parts)
            header = line[1:].strip()
            seq_parts = []
        else:
            seq_parts.append(line)
    if header is not None:
        full = header
        rid = full.split()[0]
        yield full, rid, "".join(seq_parts)


def iter_fasta_two_line(stream: TextIO) -> Generator[Tuple[str, str, str], None, None]:
    """
    Fast path for strict 2-line FASTA:
    header line, then exactly one sequence line.
    Yields (full_header, rid_token, seq).
    """
    while True:
        h = stream.readline()
        if not h:
            break
        s = stream.readline()
        if not s:
            break
        h = h.strip()
        s = s.strip()
        if not h or not h.startswith(">"):
            continue
        full = h[1:].strip()
        rid = full.split()[0]
        yield full, rid, s


def is_two_line_fasta(stream: TextIO, probe_records: int = 2000) -> bool:
    """
    Detect if FASTA looks like strict 2-line-per-record.
    Checks a probe window; if it passes, we can use iter_fasta_two_line for speed.
    """
    pos = stream.tell()
    try:
        ok = True
        for _ in range(probe_records):
            h = stream.readline()
            if not h:
                break
            s = stream.readline()
            if not s:
                ok = False
                break
            h = h.strip()
            s = s.strip()
            if not h.startswith(">") or not s or s.startswith(">"):
                ok = False
                break
        return ok
    finally:
        stream.seek(pos)


# ----------------------------
# FASTQ reader (streaming)
# ----------------------------

def iter_fastq(stream: TextIO) -> Generator[Tuple[str, str, str], None, None]:
    """
    FASTQ parser (4 lines per read).
    Yields (rid_token, seq, qual).
    """
    while True:
        h = stream.readline()
        if not h:
            break
        seq = stream.readline()
        plus = stream.readline()
        qual = stream.readline()
        if not qual:
            break

        h = h.strip()
        seq = seq.strip()
        plus = plus.strip()
        qual = qual.strip()

        if not h.startswith("@") or not plus.startswith("+"):
            continue

        rid = h[1:].split()[0]
        yield rid, seq, qual


